"""
Evaluation repository: loads walk-forward validation and backtest artifacts
(fold metrics, out-of-sample predictions, threshold/strategy comparisons)
produced by the offline training pipeline (src/06-08).

These are static evaluation results generated by the training pipeline, not
live data — loaded once at startup and cached in memory rather than re-read
per request.
"""

from pathlib import Path
from typing import Dict, List, Optional

import pandas as pd

from app.logging_config import get_logger
from app.repositories.model_repository import normalize_model_family

logger = get_logger(__name__)

# Mirrors the confidence tiers used elsewhere in the app (app/constants.py
# THRESHOLD_LOW/MEDIUM/HIGH) so the calibration curve answers the exact
# question users see on screen: "when the app says High confidence, how
# often does that historically pan out?"
CONFIDENCE_BUCKETS = [
    (0.0, 0.45, "Weak (<45%)"),
    (0.45, 0.55, "Low (45-55%)"),
    (0.55, 0.65, "Medium (55-65%)"),
    (0.65, 1.01, "High (≥65%)"),
]


def _family_suffix(family: str) -> str:
    return "" if family == "xgboost" else "_rf"


class EvaluationRepository:
    """Loads and serves model validation/backtest results per family."""

    def __init__(self, data_processed_dir: Path, project_root: Path):
        self.data_processed_dir = data_processed_dir
        self.report_dir = data_processed_dir / "report"
        self.outputs_dir = project_root / "outputs"
        self._cache: Dict[str, Optional[dict]] = {}

    def load(self) -> None:
        for family in ("xgboost", "random_forest"):
            try:
                self._cache[family] = self._load_family(family)
            except Exception as e:
                logger.error("Failed to load evaluation data for family '%s': %s", family, e)
                self._cache[family] = None
        loaded = [f for f, v in self._cache.items() if v is not None]
        logger.info("EvaluationRepository: loaded evaluation data for %s", loaded or "no families")

    def is_ready(self) -> bool:
        return any(v is not None for v in self._cache.values())

    def get(self, family: Optional[str] = None) -> Optional[dict]:
        return self._cache.get(normalize_model_family(family))

    def _load_family(self, family: str) -> dict:
        suffix = _family_suffix(family)
        buy_folds = self._read_fold_metrics(f"fold_metrics{suffix}.csv")
        sell_folds = self._read_fold_metrics(f"fold_metrics{suffix}_sell.csv")
        return {
            "buy": {
                "fold_metrics": buy_folds,
                "mean_auc": self._mean_auc(buy_folds),
                "calibration": self._compute_calibration(f"oos_predictions{suffix}.parquet", "Label_10d"),
            },
            "sell": {
                "fold_metrics": sell_folds,
                "mean_auc": self._mean_auc(sell_folds),
                "calibration": self._compute_calibration(f"oos_predictions{suffix}_sell.parquet", "Label_10d_sell"),
            },
            "thresholds": self._read_thresholds(f"summary_table{suffix}.csv"),
            "strategy_comparison": self._read_strategy_comparison(f"strategy_metrics{suffix}.csv"),
        }

    @staticmethod
    def _mean_auc(fold_metrics: List[dict]) -> Optional[float]:
        if not fold_metrics:
            return None
        return sum(f["auc"] for f in fold_metrics) / len(fold_metrics)

    def _read_fold_metrics(self, filename: str) -> List[dict]:
        df = pd.read_csv(self.data_processed_dir / filename, encoding="utf-8")
        return [
            {
                "fold": int(row["fold"]),
                "test_period": str(row["test_period"]),
                "train_rows": int(row["train_rows"]),
                "test_rows": int(row["test_rows"]),
                "auc": float(row["auc"]),
            }
            for _, row in df.iterrows()
        ]

    def _compute_calibration(self, filename: str, label_col: str) -> List[dict]:
        df = pd.read_parquet(self.data_processed_dir / filename, columns=["Pred_proba", label_col])
        buckets = []
        for lo, hi, label in CONFIDENCE_BUCKETS:
            subset = df[(df["Pred_proba"] >= lo) & (df["Pred_proba"] < hi)]
            count = len(subset)
            buckets.append({
                "label": label,
                "min_confidence": lo,
                "max_confidence": min(hi, 1.0),
                "predicted_avg": float(subset["Pred_proba"].mean()) if count else None,
                "actual_rate": float(subset[label_col].mean()) if count else None,
                "count": count,
            })
        return buckets

    def _read_thresholds(self, filename: str) -> List[dict]:
        df = pd.read_csv(self.report_dir / filename, encoding="utf-8")
        return [
            {
                "threshold": float(row["Threshold"]),
                "trades": int(row["Trades"]),
                "win_rate_pct": float(row["Win Rate %"]),
                "profit_factor": float(row["Profit Factor"]),
                "mean_return_pct": float(row["Mean Ret/Trade %"]),
                "sharpe": float(row["Sharpe (ann.)"]),
            }
            for _, row in df.iterrows()
        ]

    def _read_strategy_comparison(self, filename: str) -> List[dict]:
        df = pd.read_csv(self.outputs_dir / filename, encoding="utf-8")
        return [
            {
                "strategy": str(row["Strategy"]),
                "trades": int(row["Trades"]),
                "win_rate_pct": float(row["Win Rate %"]),
                "profit_factor": float(row["Profit Factor"]),
                "mean_return_pct": float(row["Mean Ret %"]),
                "sharpe": float(row["Sharpe"]),
            }
            for _, row in df.iterrows()
        ]
